const {chromium}=require('playwright');
const assert=require('node:assert/strict');
process.loadEnvFile('/workspace/sistemapdv/.pdv-local/development.env');
(async()=>{
 const base=process.env.PDV_WEB_URL || 'http://127.0.0.1:5175';
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.setDefaultTimeout(12000);
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/login');
 await page.getByLabel('Usuário',{exact:true}).fill('admin.dev');
 await page.getByLabel('Senha',{exact:true}).fill(process.env.DEV_ADMIN_PASSWORD);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.waitForURL(base+'/');
 const token=await page.evaluate(()=>localStorage.getItem('token'));
 const headers={Authorization:`Bearer ${token}`};
 if(!(await (await page.request.get(base+'/api/cash-register/status',{headers})).json()).is_open) await page.request.post(base+'/api/cash-register/open',{headers,data:{opening_amount:0}});
 const stamp=Date.now();
 const tableResponse=await page.request.post(base+'/api/tables',{headers,data:{tableNumber:Math.floor(Math.random()*1000000)+1000,capacity:4}});
 assert.equal(tableResponse.status(),201);
 const {table}=await tableResponse.json();
 const productResponse=await page.request.post(base+'/api/products',{headers,data:{name:`Produto navegador ${stamp}`,category:'comidas',unitOfMeasure:'unidade',costPrice:5,salePrice:15}});
 assert.equal(productResponse.status(),201);
 const {product}=await productResponse.json();
 assert.equal((await page.request.post(base+'/api/stock/add',{headers,data:{productId:product.id,quantity:10}})).status(),201);
 await page.getByRole('link',{name:'Fila de Espera',exact:true}).click();
 await page.getByRole('heading',{name:'Fila de espera',exact:true}).waitFor();
 await page.getByRole('button',{name:'Adicionar cliente',exact:true}).click();
 const client=`Cliente navegador ${stamp}`;
 await page.getByLabel('Nome do cliente',{exact:true}).fill(client);
 await page.getByLabel('Quantidade de pessoas',{exact:true}).fill('3');
 await page.getByRole('button',{name:'Adicionar à fila',exact:true}).click();
 await page.getByRole('heading',{name:client,exact:true}).waitFor();
 await page.getByRole('heading',{name:client,exact:true}).locator('xpath=../../..').getByRole('button',{name:'Acomodar',exact:true}).click();
 await page.getByLabel('Mesa disponível',{exact:true}).selectOption(table.id);
 await page.getByRole('button',{name:'Acomodar e abrir comanda',exact:true}).click();
 await page.getByRole('button',{name:'Abrir comanda',exact:true}).click();
 await page.getByRole('dialog').filter({has:page.getByText('Itens da Comanda',{exact:true})}).waitFor();
 await page.getByRole('button',{name:'Adicionar Item',exact:true}).click();
 const addDialog=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Adicionar Item à Comanda',exact:true})});
 await addDialog.getByRole('combobox').click();
 await page.getByRole('option',{name:new RegExp(product.name)}).click();
 await page.getByLabel('Quantidade',{exact:true}).fill('2');
 await addDialog.getByRole('button',{name:'Adicionar',exact:true}).click();
 await page.getByRole('cell',{name:product.name,exact:true}).waitFor();
 await page.screenshot({path:'/workspace/sistemapdv/.pdv-local/comanda-browser.png',fullPage:true});
 await page.getByRole('button',{name:'Fechar Comanda',exact:true}).click();
 const closeDialog=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Fechar Comanda',exact:true})});
 await closeDialog.getByRole('combobox').first().click();
 await page.getByRole('option',{name:'PIX',exact:true}).click();
 await closeDialog.getByRole('button',{name:'Fechar Comanda',exact:true}).click();
 await page.getByText('Comanda fechada com sucesso!',{exact:true}).waitFor();
 const tableCheck=await (await page.request.get(base+`/api/tables/${table.id}`,{headers})).json();
 assert.equal(tableCheck.status,'disponivel');
 assert.equal(Number((await (await page.request.get(base+`/api/products/${product.id}`,{headers})).json()).currentStock),8);
 await page.goto(base+'/queue');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('heading',{name:'Fila de espera',exact:true}).waitFor();
 await page.screenshot({path:'/workspace/sistemapdv/.pdv-local/fila-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Sem rolagem horizontal no celular');
 assert.deepEqual(errors,[]);
 console.log('Navegador aprovado: login, cadastro na fila, acomodação, abertura da comanda, inclusão de produto, pagamento, mesa livre e layout móvel.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e.message);process.exit(1)});
