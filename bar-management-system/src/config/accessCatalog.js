// Suggested profiles include the reads required by their operations.
function expand(ids) {
  const result = new Set(ids);
  let size;
  do {
    size = result.size;
    for (const id of result)
      for (const dependency of dependencies[id] || []) result.add(dependency);
  } while (size !== result.size);
  return [...result].sort();
}
